await call('evil','ack',{ids:[seq]});assert.equal((await (await call('b','inbox')).json()).messages.length,1,'other device cannot delete recipient messages');
await call('b','ack',{ids:[seq]});assert.equal((await (await call('b','inbox')).json()).messages.length,0);
assert.equal((await call('a','send',{to:b.cloudId,message:{...message,id:'invalid-media',kind:'image',url:'javascript:alert(1)'}})).status,400);
