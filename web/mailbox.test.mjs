const b=await (await call('b','register',{id:'yueliao-bob',name:'Bob',language:'vi'})).json();
const evil=await (await call('evil','register',{id:'yueliao-alice',name:'Spoof Alice',language:'zh'})).json();
const message={id:'message-1234',kind:'text',text:'离线留言',lang:'zh'};
