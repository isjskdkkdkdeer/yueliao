const fetchImpl=(path,options)=>handleMailboxApi(new Request('https://example.com'+path,options),{DB});
const received=[];
let senderCloud,recipientCloud;
const sender=createMailboxClient({profile:{id:'client-sender',name:'发信人',language:'zh'},fetchImpl,storage:storage(),onIdentity:id=>senderCloud=id});
