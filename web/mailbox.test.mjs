assert.ok(!JSON.stringify(inbox).includes(tokens.a),'raw device secret is never returned');
console.log('PASS mailbox: durable offline delivery, receiver authorization, device isolation, retry deduplication, acknowledgement ownership, expiry, unsafe media rejection, secret isolation.');
